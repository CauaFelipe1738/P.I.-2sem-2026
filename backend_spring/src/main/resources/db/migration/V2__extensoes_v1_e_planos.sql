CREATE TABLE plano_acompanhamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id BIGINT NOT NULL,
    professor_id BIGINT NOT NULL,
    disciplina_turma_id BIGINT,
    dificuldade VARCHAR(500) NOT NULL,
    objetivo VARCHAR(500) NOT NULL,
    acao_proposta VARCHAR(1000) NOT NULL,
    data_inicio DATE NOT NULL,
    prazo DATE NOT NULL,
    status VARCHAR(30) NOT NULL,
    resultado VARCHAR(1000),
    CONSTRAINT fk_plano_aluno FOREIGN KEY (aluno_id) REFERENCES aluno(id),
    CONSTRAINT fk_plano_professor FOREIGN KEY (professor_id) REFERENCES professor(id),
    CONSTRAINT ck_plano_prazo CHECK (prazo >= data_inicio)
);

