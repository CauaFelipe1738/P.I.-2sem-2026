CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(150) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    nome_completo VARCHAR(150) NOT NULL,
    cargo VARCHAR(40) NOT NULL,
    perfil_id BIGINT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_criacao TIMESTAMP NOT NULL,
    ultimo_acesso TIMESTAMP,
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

CREATE TABLE professor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    nome_completo VARCHAR(150) NOT NULL,
    formacao VARCHAR(150),
    CONSTRAINT fk_professor_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);

CREATE TABLE aluno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    nome_completo VARCHAR(150) NOT NULL,
    data_nascimento DATE,
    data_ingresso DATE NOT NULL,
    matricula VARCHAR(50) NOT NULL,
    CONSTRAINT uk_aluno_matricula UNIQUE (matricula)
);

CREATE TABLE periodo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_periodo VARCHAR(80) NOT NULL,
    ano_letivo INTEGER NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL
);

CREATE TABLE curso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(160) NOT NULL,
    descricao VARCHAR(1000),
    carga_horaria INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL
);

CREATE TABLE turma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curso_id BIGINT NOT NULL,
    periodo_id BIGINT NOT NULL,
    nome_turma VARCHAR(80) NOT NULL,
    turno VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    CONSTRAINT fk_turma_curso FOREIGN KEY (curso_id) REFERENCES curso(id),
    CONSTRAINT fk_turma_periodo FOREIGN KEY (periodo_id) REFERENCES periodo(id)
);

CREATE TABLE disciplina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(160) NOT NULL,
    descricao VARCHAR(1000),
    carga_horaria INTEGER NOT NULL
);

CREATE TABLE disciplina_turma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_id BIGINT NOT NULL,
    turma_id BIGINT NOT NULL,
    CONSTRAINT fk_dt_disciplina FOREIGN KEY (disciplina_id) REFERENCES disciplina(id),
    CONSTRAINT fk_dt_turma FOREIGN KEY (turma_id) REFERENCES turma(id)
);

CREATE TABLE professor_disciplina_turma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id BIGINT NOT NULL,
    disciplina_turma_id BIGINT NOT NULL,
    CONSTRAINT fk_pdt_professor FOREIGN KEY (professor_id) REFERENCES professor(id),
    CONSTRAINT fk_pdt_dt FOREIGN KEY (disciplina_turma_id) REFERENCES disciplina_turma(id)
);

CREATE TABLE matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id BIGINT NOT NULL,
    turma_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    data_matricula DATE NOT NULL,
    data_desligamento DATE,
    CONSTRAINT fk_matricula_aluno FOREIGN KEY (aluno_id) REFERENCES aluno(id),
    CONSTRAINT fk_matricula_turma FOREIGN KEY (turma_id) REFERENCES turma(id)
);

CREATE TABLE aula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_turma_id BIGINT NOT NULL,
    professor_id BIGINT NOT NULL,
    data_aula DATE NOT NULL,
    horario_inicio TIME NOT NULL,
    horario_fim TIME NOT NULL,
    conteudo VARCHAR(1000),
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_aula_dt FOREIGN KEY (disciplina_turma_id) REFERENCES disciplina_turma(id),
    CONSTRAINT fk_aula_professor FOREIGN KEY (professor_id) REFERENCES professor(id)
);

CREATE TABLE frequencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aula_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    presente BOOLEAN NOT NULL,
    justificativa VARCHAR(500),
    CONSTRAINT fk_frequencia_aula FOREIGN KEY (aula_id) REFERENCES aula(id),
    CONSTRAINT fk_frequencia_aluno FOREIGN KEY (aluno_id) REFERENCES aluno(id),
    CONSTRAINT uk_frequencia_aula_aluno UNIQUE (aula_id, aluno_id)
);

CREATE TABLE avaliacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_turma_id BIGINT NOT NULL,
    professor_id BIGINT NOT NULL,
    periodo_id BIGINT NOT NULL,
    nome_avaliacao VARCHAR(150) NOT NULL,
    tipo_avaliacao VARCHAR(30) NOT NULL,
    descricao VARCHAR(1000),
    data_avaliacao DATE NOT NULL,
    valor_total NUMERIC(5,2) NOT NULL CHECK (valor_total > 0),
    peso NUMERIC(5,2) NOT NULL CHECK (peso > 0),
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_avaliacao_dt FOREIGN KEY (disciplina_turma_id) REFERENCES disciplina_turma(id)
);

CREATE TABLE aluno_avaliacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    avaliacao_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    nota NUMERIC(5,2) CHECK (nota IS NULL OR nota >= 0),
    observacao VARCHAR(1000),
    CONSTRAINT fk_aa_avaliacao FOREIGN KEY (avaliacao_id) REFERENCES avaliacao(id),
    CONSTRAINT fk_aa_aluno FOREIGN KEY (aluno_id) REFERENCES aluno(id),
    CONSTRAINT uk_aluno_avaliacao UNIQUE (avaliacao_id, aluno_id)
);

CREATE TABLE comentario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id BIGINT NOT NULL,
    professor_id BIGINT NOT NULL,
    disciplina_turma_id BIGINT,
    titulo VARCHAR(200) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    classificacao VARCHAR(30) NOT NULL,
    descricao VARCHAR(2000) NOT NULL,
    data_comentario TIMESTAMP NOT NULL,
    CONSTRAINT fk_comentario_aluno FOREIGN KEY (aluno_id) REFERENCES aluno(id),
    CONSTRAINT fk_comentario_professor FOREIGN KEY (professor_id) REFERENCES professor(id)
);

CREATE TABLE auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT,
    tabela_modificada VARCHAR(100) NOT NULL,
    operacao VARCHAR(30) NOT NULL,
    dados_anteriores VARCHAR(4000),
    dados_novos VARCHAR(4000),
    data_hora TIMESTAMP NOT NULL,
    endereco_ip VARCHAR(45)
);

CREATE INDEX idx_aula_dt ON aula (disciplina_turma_id);
CREATE INDEX idx_frequencia_aluno ON frequencia (aluno_id);
CREATE INDEX idx_avaliacao_dt ON avaliacao (disciplina_turma_id);
CREATE INDEX idx_matricula_turma ON matricula (turma_id);
